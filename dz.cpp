#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "ru");

    //1 задание
    cout << "копирование массива\n";
    int arr1[5] = { 1, 2, 3, 4, 5 };
    int arr2[5];

    int* p1 = arr1; // указатель на первый массив
    int* p2 = arr2; // указатель на второй массив

    cout << "исходный массив: ";
    for (int i = 0; i < 5; i++) {
        cout << *(p1 + i) << " ";
    }
    cout << "\n";

    // копирование через указатели
    for (int i = 0; i < 5; i++) {
        *(p2 + i) = *(p1 + i);
    }

    cout << "скопированный массив: ";
    for (int i = 0; i < 5; i++) {
        cout << *(p2 + i) << " ";
    }
    cout << "\n\n";

    //2 задание
    cout << "2 задание - обратный порядок в массиве\n";
    int arr3[5] = { 10, 20, 30, 40, 50 };

    int* p3 = arr3; // указатель на массив

    cout << "массив до: ";
    for (int i = 0; i < 5; i++) {
        cout << *(p3 + i) << " ";
    }
    cout << "\n";

    // меняем порядок на противоположный
    for (int i = 0; i < 2; i++) {
        int temp = *(p3 + i);
        *(p3 + i) = *(p3 + 4 - i);
        *(p3 + 4 - i) = temp;
    }

    cout << "массив после: ";
    for (int i = 0; i < 5; i++) {
        cout << *(p3 + i) << " ";
    }
    cout << "\n\n";

    //3 задание
    cout << "3 задание - копирование в обратном порядке\n";
    int arr4[5] = { 100, 200, 300, 400, 500 };
    int arr5[5];

    int* p4 = arr4; // указатель на исходный массив
    int* p5 = arr5; // указатель на целевой массив

    cout << "исходный массив: ";
    for (int i = 0; i < 5; i++) {
        cout << *(p4 + i) << " ";
    }
    cout << "\n";

    // копирование в обратном порядке
    for (int i = 0; i < 5; i++) {
        *(p5 + i) = *(p4 + 4 - i);
    }

    cout << "массив в обратном порядке: ";
    for (int i = 0; i < 5; i++) {
        cout << *(p5 + i) << " ";
    }
    cout << "\n";

    return 0;
}